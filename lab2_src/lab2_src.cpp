#include <iostream>
#include <sstream>
#include <string>
#include <cmath>
#include <iomanip>

int main()
{
   
    //добавка кириллической локали
	std::setlocale(LC_ALL, "ru_RU.UTF-8");
    //вывод имен переменных при вводе, чтобы пользователь понимал, что он вводит
    const std::string var_names[2] = {"режим вычисления:", "значение x:" /*"погрешность eps:",  "режим вывода дробного числа:", "число слагаемых:"*/};
     

    double x = 0,   //значение аргумента функции
    eps = 0, //погрешность функции
    u = 0, 
    y = 0;
    int m = 0,  //номер способа вычисления функции
    k = 1, //номер слагаемого k
    n = 0; //кол - во первых слагаемых
 
   
	std::string line;//строка, из которой передается значение
    
  
    //последовательный ввод четырёх переменных(m, fl, x)  + (eps или k) с проверкой типов
   
    //вводятся 2 переменных(m, x)
    for(int i = 0; i < 2; i++)
    {
        std::cout << var_names[i] << std::endl;
        while (std::getline(std::cin, line))
        {
            std::stringstream ss(line); // символьный поток

            // каждый раз указатель хранит адрес другой переменной
            if (i == 0 && ss >> m)
            {
                if (ss.eof() && (m >= 1 && m <= 3))
                {

                    break;
                }
                std::cout << "способа вычисления функции с таким номером не существует." << std::endl;
            }
            else if (i == 1 && ss >> x)
            {
                if (ss.eof() && (x > 0 && x <= 2))
                {

                    break;
                }
                std::cout << "число x не входит в диапазон сходимости ряда (0 < x <= 2)." << std::endl;
            }
            std::cout << var_names[i] << std::endl;
        }
    }
    ///////////////////////////////////////
    
    u = (x - 1.0);

    //выбор способа вычисления
    switch (m)
    {
        case 1: //первый способ(вычисление суммы ряда с заданной точностью)
            std::cout << "погрешность:" << std::endl;
            while (std::getline(std::cin, line)) // циклический ввод погрешности
            {
                std::stringstream ss(line); // символьный поток
                if (ss >> eps)
                {
                    if (ss.eof() && (eps > 0 && eps < 1))
                    {
                        break;
                    }
                }
                std::cout << "погрешность не входит в диапазон (0, 1)" << std::endl;
                std::cout << "погрешность:" << std::endl;
            }

            while (std::abs(u) > eps)
            { // вычисление суммы ряда по формуле
                y = y + u; //суммирование ряда
                k = k + 1;
                u = (-u) * (x - 1.0) * (k - 1) / k; //вычисление следующего  слагаемого
            }
        break;

        case 2://второй режим(вычисление суммы ряда с числом слагаемых n)
            std::cout << "число членов ряда суммы:" << std::endl;
            while (std::getline(std::cin, line)) // циклический ввод числа слагаемых n
            {
                std::stringstream ss(line); // символьный поток
                if (ss >> n)
                {
                    if (ss.eof() && (n >= 2))
                    {
                        break;
                    }
                }
                std::cout << "число членов ряда суммы должно быть целым и входить в диапазон [2; +бесконечность)" << std::endl;
                std::cout << "число членов ряда суммы:" << std::endl;
            }
            for (k = k + 1; k <= n; k++)
            {
                y = y + u;
                u = -u * (x - 1.0) * (k - 1) / k;
            }
        break;
    
        case 3:
            y = std::log(x);
        break;

       default:
           break;
    }
    
    //вывод результата
    if(m == 1) //при использовании первого способа вычисления суммы ряда
    {
        //результат выводится в трёх разных представлениях
        std::cout << "значение функции ln " << x << " равно " << y << std::endl; //без манипуляторов
        std::cout << "значение функции ln " << x << " равно " << std::setprecision(8) << y << std::endl; //точность восемь знаков после запятой
        std::cout << "значение функции ln " << x << " равно " << std::scientific << y << std::endl; //в научном виде
    }
    else // в противном случае результат выводится без манипуляторов
    {
        std::cout << "значение функции ln " << x << "равно" << y << std::endl;
    }
  
    return 0;
}